-- Inmutabilidad append-only: trigger en PostgreSQL (V27 Java).
-- En H2/tests la protección queda en el servicio; esta tabla marca el cumplimiento en BD.

CREATE TABLE IF NOT EXISTS vacacion_proteccion_legal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(255) NOT NULL
);

INSERT INTO vacacion_proteccion_legal (descripcion)
SELECT 'evento_solicitud_vacaciones_append_only'
WHERE NOT EXISTS (
    SELECT 1 FROM vacacion_proteccion_legal WHERE descripcion = 'evento_solicitud_vacaciones_append_only'
);
