CREATE TABLE IF NOT EXISTS recibo_proteccion_legal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(255) NOT NULL
);

INSERT INTO recibo_proteccion_legal (descripcion)
SELECT 'eventos_firma_append_only_via_servicio'
WHERE NOT EXISTS (
    SELECT 1 FROM recibo_proteccion_legal WHERE descripcion = 'eventos_firma_append_only_via_servicio'
);
