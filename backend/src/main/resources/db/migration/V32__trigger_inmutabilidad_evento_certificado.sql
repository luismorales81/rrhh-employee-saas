-- Inmutabilidad append-only: trigger en PostgreSQL (V31 Java).
-- En H2/tests la protección queda en el servicio; esta tabla marca el cumplimiento en BD.

CREATE TABLE IF NOT EXISTS certificado_proteccion_legal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(255) NOT NULL
);

INSERT INTO certificado_proteccion_legal (descripcion)
SELECT 'evento_certificado_append_only'
WHERE NOT EXISTS (
    SELECT 1 FROM certificado_proteccion_legal WHERE descripcion = 'evento_certificado_append_only'
);
